export function getJob(id: string) {
  return jobs.find((j) => j.id === id);
}

/** Valor mensal aproximado em USD apenas para ordenação na demonstração. */
export function monthlyUsd(job: Job) {
  if (!job.salary) return 0;
  const rate = { BRL: 0.19, USD: 1, EUR: 1.08 }[job.salary.currency];
  const mult = { month: 1, hour: 160, year: 1 / 12 }[job.salary.period];
  return job.salary.max * rate * mult;
}
